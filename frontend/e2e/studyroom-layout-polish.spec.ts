import {test,expect} from './fixtures/studyroom';
import {directory,resourcePage} from './fixtures/classroom-navigation';

test('keeps original classroom styling with a collapsible brand rail, uniform tools and a complete quiz canvas',async({page})=>{
 await page.setViewportSize({width:1366,height:900});
 await page.route('**/presentation/slides/harness-stack-slide/image',route=>route.fulfill({contentType:'image/svg+xml',body:'<svg xmlns="http://www.w3.org/2000/svg" width="800" height="600"><rect width="800" height="600" fill="white"/><rect width="800" height="90" fill="#476fba"/><text x="45" y="58" fill="white" font-size="30">Stack / last in, first out</text><rect x="210" y="210" width="120" height="100" fill="#eee" stroke="#777"/><rect x="330" y="210" width="120" height="100" fill="#ddd" stroke="#777"/><text x="255" y="270" font-size="28">1</text><text x="375" y="270" font-size="28">2</text><text x="350" y="360" font-size="24">top</text></svg>'}));
 await page.goto('/studyroom');
 await page.getByLabel('课程问题',{exact:true}).fill('栈的定义和C代码阅读，讲述框选回归，课堂布局回归');
 await page.getByRole('button',{name:'生成大纲',exact:true}).click();
 await page.getByRole('button',{name:'审阅大纲',exact:true}).click();
 await expect(page.getByRole('button',{name:'确认大纲，开始学习'})).toBeEnabled();
 await page.getByRole('button',{name:'确认大纲，开始学习'}).click();
 await expect(page).toHaveURL(/\/studyroom\/[a-f0-9-]+$/);
 await expect(page.locator('.classroom-navigation .course-brand')).toBeVisible();
 expect(await page.locator('.stage__brand').count()).toBe(0);
 expect(await page.locator('.stage__theme').count()).toBe(0);
 await expect(page.locator('.studyroom-header [data-theme-toggle]')).toBeVisible();
 expect(await page.locator('.course-info,.point-objective').count()).toBe(0);
 await expect(page.getByLabel('当前讲述字幕')).toBeVisible();
 const dock=await page.locator('.lecture-narration').boundingBox();
 const toolbar=await page.locator('.lecture-buttons').boundingBox();
 expect(dock!.y).toBeGreaterThanOrEqual(toolbar!.y+toolbar!.height-1);
 expect(dock!.height).toBeGreaterThanOrEqual(100);
 const icons=await page.locator('.lecture-buttons svg').evaluateAll(elements=>elements.map(e=>({width:e.getBoundingClientRect().width,height:e.getBoundingClientRect().height})));
 expect(icons.length).toBeGreaterThan(5);
 expect(icons.every(icon=>icon.width===18&&icon.height===18)).toBe(true);
 await page.screenshot({path:'test-results/layout-polish-desktop.png',fullPage:true});
 await page.getByRole('button',{name:'完整讲述',exact:true}).click();
 await expect(page.getByLabel('完整讲解正文')).toBeVisible();
 await page.getByRole('button',{name:'全屏',exact:true}).click();
 await expect.poll(()=>page.evaluate(()=>document.fullscreenElement?.classList.contains('studyroom'))).toBe(true);
 await expect(page.locator('.classroom-navigation')).toBeHidden();
 await expect(page.locator('.classroom-workspace-header')).toBeHidden();
 await expect(page.getByLabel('完整讲解正文')).toBeHidden();
 await expect(page.getByLabel('当前讲述字幕')).toBeVisible();
 await expect.poll(async()=>{
  const material=await page.getByLabel('当前学习材料',{exact:true}).boundingBox();
  return material!.x<10&&material!.y<10&&material!.width>1300;
 }).toBe(true);
 await page.screenshot({path:'test-results/layout-polish-fullscreen.png',fullPage:true});
 await page.getByRole('button',{name:'退出全屏',exact:true}).click();
 await expect.poll(()=>page.evaluate(()=>document.fullscreenElement===null)).toBe(true);
 await expect(page.locator('.classroom-navigation')).toBeVisible();
 await expect(page.locator('.classroom-workspace-header')).toBeVisible();
 await expect(page.getByLabel('完整讲解正文')).toBeVisible();
 await page.getByRole('button',{name:'收起完整讲述',exact:true}).click();
 await page.setViewportSize({width:920,height:900});
 await page.getByRole('button',{name:'完整讲述',exact:true}).click();
 await expect(page.getByLabel('完整讲解正文')).toBeVisible();
 await expect.poll(async()=>{
  const groups=await page.locator('.lecture-buttons').evaluate(element=>[...element.children].map(child=>{const rect=child.getBoundingClientRect();return{x:rect.x,right:rect.right,y:rect.y,bottom:rect.bottom};}));
  const [start,center,end]=groups;
  return center!.y>=Math.max(start!.bottom,end!.bottom)-1;
 }).toBe(true);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:'test-results/layout-polish-narrow.png',fullPage:true});
 await page.getByRole('button',{name:'收起完整讲述',exact:true}).click();
 await page.setViewportSize({width:1366,height:900});
 await page.getByRole('button',{name:'收起课程目录',exact:true}).click();
 await expect(page.locator('.classroom-navigation')).toHaveAttribute('inert','');
 await expect(page.getByRole('button',{name:'展开课程目录',exact:true})).toHaveCount(0);
 await expect(page.getByRole('button',{name:'课程目录',exact:true})).toBeFocused();
 await resourcePage(page,/栈的定义与代码课件/);
 expect(await page.locator('.slide-toolbar,.slide-caption,.slide-directory').count()).toBe(0);
 await expect(page.getByRole('button',{name:'全屏',exact:true})).toHaveCount(1);
 await resourcePage(page,/小测/);
 const quiz=page.getByLabel('知识点小测').filter({visible:true});
 if(await quiz.getByRole('button',{name:'重新准备小测',exact:true}).isVisible())await quiz.getByRole('button',{name:'重新准备小测',exact:true}).click();
 await expect(quiz.locator('form')).toHaveCount(1);
 await expect(quiz).toContainText('第 1 / 3 题');
 expect(await page.locator('.resource-page:visible').count()).toBe(1);
 const frame=await page.locator('.resource-page:visible').boundingBox();
 const panel=await quiz.boundingBox();
 expect(Math.abs(panel!.x+panel!.width/2-frame!.x-frame!.width/2)).toBeLessThan(3);
 if(panel!.height<frame!.height)expect(Math.abs(panel!.y+panel!.height/2-frame!.y-frame!.height/2)).toBeLessThan(3);
 await quiz.getByRole('radio').first().check();
 const chosen=await quiz.getByRole('radio').first().getAttribute('value');
 await quiz.getByRole('button',{name:'下一题',exact:true}).click();
 await expect(quiz).toContainText('第 2 / 3 题');
 await quiz.getByRole('button',{name:'上一题',exact:true}).click();
 await expect(quiz.locator(`input[value="${chosen}"]`)).toBeChecked();
 await expect(quiz.locator('form')).toHaveCSS('opacity','1');
 await page.screenshot({path:'test-results/layout-polish-quiz.png',fullPage:true});
 for(const viewport of [{width:390,height:844},{width:844,height:390}]){
  await page.setViewportSize(viewport);await page.emulateMedia({reducedMotion:'reduce'});
  await directory(page,false);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth&&document.documentElement.scrollHeight<=innerHeight+1)).toBe(true);
  await expect(page.getByLabel('当前讲述字幕')).toBeVisible();
  const bounds=await page.locator('.lecture-narration').boundingBox();
  expect(bounds!.y+bounds!.height).toBeLessThanOrEqual(viewport.height);
  await page.screenshot({path:`test-results/layout-polish-${viewport.width}.png`,fullPage:true});
 }
});
