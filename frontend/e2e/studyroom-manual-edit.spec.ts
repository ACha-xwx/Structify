import {test,expect} from './fixtures/studyroom';

test('human edits persist through collapse, save and reload; blank feedback never invokes AI',async({page},testInfo)=>{
 await page.setViewportSize({width:1366,height:900});
 await page.goto('/studyroom');
 await page.getByLabel('课程问题',{exact:true}).fill('栈的定义和C代码阅读，人工大纲编辑');
 await page.getByRole('button',{name:'生成大纲',exact:true}).click();
 await expect(page).toHaveURL(/\/studyroom\/outlines\//);
 await expect(page.getByRole('button',{name:'审阅大纲',exact:true})).toBeVisible();
 await expect(page.locator('.stage-change-enter-active, .review-card-enter-active')).toHaveCount(0);
 await page.screenshot({path:testInfo.outputPath('outline-collapsed.png')});
 await page.getByRole('button',{name:'审阅大纲',exact:true}).click();
 const titles=page.getByLabel('知识点标题',{exact:true});
 await expect(titles.first()).toBeVisible();
 const initial=await titles.count();
 const firstTitle=await titles.first().inputValue();
 await titles.first().fill('人工调整：栈的基础');
 await page.getByRole('button',{name:'收起大纲',exact:true}).click();
 await page.getByRole('button',{name:'审阅大纲',exact:true}).click();
 await expect(titles.first()).toHaveValue('人工调整：栈的基础');
 await expect(page.getByRole('button',{name:'确认大纲，开始学习'})).toBeDisabled();
 await page.getByRole('button',{name:'拖动知识点',exact:true}).first().focus();
 await page.getByRole('button',{name:'拖动知识点',exact:true}).first().press('Control+ArrowDown');
 await expect(titles.nth(1)).toHaveValue('人工调整：栈的基础');
 await page.getByRole('button',{name:'拖动知识点',exact:true}).first().dragTo(page.locator('.outline-unit').nth(1),{targetPosition:{x:90,y:25}});
 await expect(titles.first()).toHaveValue('人工调整：栈的基础');
 await page.getByRole('button',{name:'拖动知识点',exact:true}).first().focus();
 await page.getByRole('button',{name:'拖动知识点',exact:true}).first().press('Control+ArrowDown');
 await page.getByRole('button',{name:'删除知识点',exact:true}).last().click();
 await expect(titles).toHaveCount(initial-1);
 await page.getByRole('button',{name:'撤销删除',exact:true}).click();
 await expect(titles).toHaveCount(initial);
 await page.getByRole('button',{name:'添加知识点',exact:true}).last().click();
 await expect(titles).toHaveCount(initial+1);
 await titles.last().fill('栈的人工补充');
 await page.getByLabel('知识点目标',{exact:true}).last().fill('解释栈顶指针并描述一次入栈操作');
 const saved=page.waitForResponse(response=>response.request().method()==='POST'&&response.url().endsWith('/manual-revisions'));
 await page.getByRole('button',{name:'保存修改',exact:true}).click();
 expect((await saved).ok()).toBeTruthy();
 await expect(page.getByRole('button',{name:'确认大纲，开始学习'})).toBeEnabled();
 await page.reload();
 await page.getByRole('button',{name:'审阅大纲',exact:true}).click();
 await expect(titles.nth(1)).toHaveValue('人工调整：栈的基础');
 await expect(titles.last()).toHaveValue('栈的人工补充');
 await expect(page.locator('.review-card-leave-active, .review-panel-enter-active')).toHaveCount(0);
 await page.screenshot({path:testInfo.outputPath('outline-expanded-editor.png')});
 expect(await titles.first().inputValue()).not.toBe(firstTitle);
 let revisions=0;
 page.on('request',request=>{if(request.method()==='POST'&&/\/revisions$/.test(request.url()))revisions++;});
 await page.getByRole('button',{name:'修改大纲',exact:true}).click();
 await page.getByLabel('修改意见',{exact:true}).fill('   ');
 await expect(page.getByRole('button',{name:'按意见调整大纲',exact:true})).toBeDisabled();
 expect(revisions).toBe(0);
 await page.screenshot({path:testInfo.outputPath('outline-blank-ai-feedback.png')});
});
